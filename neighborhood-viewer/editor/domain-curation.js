(() => {
  'use strict';

  const EDITOR_VERSION = '1.0.0';
  const DEFAULT_COLOR = '#d7dce2';
  const PALETTE = [
    '#4E79A7', '#F28E2B', '#E15759', '#76B7B2', '#59A14F',
    '#EDC948', '#B07AA1', '#FF9DA7', '#9C755F', '#BAB0AC',
    '#2F5597', '#00A6A6', '#D45087', '#7A5195', '#EF5675',
    '#FFA600', '#3A86FF', '#8338EC', '#FB5607', '#2A9D8F',
    '#8ECAE6', '#219EBC', '#023047', '#FFB703', '#E76F51',
    '#90BE6D', '#577590', '#F94144', '#43AA8B', '#F8961E'
  ];

  function clean(value) {
    return value == null ? '' : String(value).trim();
  }

  function lower(value) {
    return clean(value).toLocaleLowerCase();
  }

  function numberText(value) {
    return Number(value || 0).toLocaleString('en-US');
  }

  function validHex(value) {
    return /^#[0-9a-f]{6}$/i.test(clean(value));
  }

  function normalizeHex(value, fallback = DEFAULT_COLOR) {
    const text = clean(value);
    if (/^#[0-9a-f]{3}$/i.test(text)) {
      return `#${text[1]}${text[1]}${text[2]}${text[2]}${text[3]}${text[3]}`.toUpperCase();
    }
    return validHex(text) ? text.toUpperCase() : fallback;
  }

  function hashString(value) {
    let hash = 2166136261;
    const text = String(value);
    for (let i = 0; i < text.length; i += 1) {
      hash ^= text.charCodeAt(i);
      hash = Math.imul(hash, 16777619);
    }
    return hash >>> 0;
  }

  function hslToHex(h, s, l) {
    const saturation = s / 100;
    const lightness = l / 100;
    const c = (1 - Math.abs(2 * lightness - 1)) * saturation;
    const x = c * (1 - Math.abs(((h / 60) % 2) - 1));
    const m = lightness - c / 2;
    let r = 0;
    let g = 0;
    let b = 0;
    if (h < 60) [r, g, b] = [c, x, 0];
    else if (h < 120) [r, g, b] = [x, c, 0];
    else if (h < 180) [r, g, b] = [0, c, x];
    else if (h < 240) [r, g, b] = [0, x, c];
    else if (h < 300) [r, g, b] = [x, 0, c];
    else [r, g, b] = [c, 0, x];
    const channel = value => Math.round((value + m) * 255).toString(16).padStart(2, '0');
    return `#${channel(r)}${channel(g)}${channel(b)}`.toUpperCase();
  }

  function suggestedColor(index, key) {
    if (index < PALETTE.length) return PALETTE[index];
    const hue = (index * 137.508 + (hashString(key) % 29)) % 360;
    const saturation = 58 + (index % 3) * 8;
    const lightness = 43 + (index % 4) * 5;
    return hslToHex(hue, Math.min(82, saturation), Math.min(62, lightness));
  }

  function yamlQuote(value) {
    return `"${String(value)
      .replace(/\\/g, '\\\\')
      .replace(/"/g, '\\"')
      .replace(/\r/g, '\\r')
      .replace(/\n/g, '\\n')}"`;
  }

  function serializeFlatYaml(object, headerLines = []) {
    const entries = Object.entries(object).sort(([a], [b]) => a.localeCompare(b));
    const lines = [
      `# Generated by EvoSupplement Gene Neighborhood Editor ${EDITOR_VERSION}`,
      ...headerLines.map(line => `# ${line}`)
    ];
    if (!entries.length) lines.push('# No entries selected.');
    for (const [key, value] of entries) lines.push(`${yamlQuote(key)}: ${yamlQuote(value)}`);
    return `${lines.join('\n')}\n`;
  }

  function downloadBlob(filename, blob) {
    const url = URL.createObjectURL(blob);
    const link = document.createElement('a');
    link.href = url;
    link.download = filename;
    document.body.appendChild(link);
    link.click();
    link.remove();
    window.setTimeout(() => URL.revokeObjectURL(url), 1500);
  }

  function copyObject(value) {
    const result = Object.create(null);
    if (!value || typeof value !== 'object' || Array.isArray(value)) return result;
    for (const [key, mapped] of Object.entries(value)) {
      const normalized = clean(key);
      if (normalized) result[normalized] = clean(mapped);
    }
    return result;
  }

  function findMappedEntry(object, candidates) {
    const entries = Object.entries(object);
    for (const candidate of candidates) {
      const exact = entries.find(([key]) => key === candidate);
      if (exact) return { key: exact[0], value: exact[1] };
    }
    const candidateSet = new Set(candidates.map(lower));
    const insensitive = entries.find(([key]) => candidateSet.has(lower(key)));
    return insensitive ? { key: insensitive[0], value: insensitive[1] } : null;
  }

  function removeMappedEntries(object, candidates) {
    const candidateSet = new Set(candidates.map(lower));
    for (const key of Object.keys(object)) {
      if (candidateSet.has(lower(key))) delete object[key];
    }
  }

  function createEditor(viewer, ids) {
    const elements = {};
    for (const [key, id] of Object.entries(ids)) elements[key] = document.getElementById(id);

    const state = {
      loaded: false,
      records: new Map(),
      allStats: new Map(),
      visibleStats: new Map(),
      selectedRawName: '',
      initialRenames: Object.create(null),
      initialColors: Object.create(null),
      unmatchedRenames: Object.create(null),
      unmatchedColors: Object.create(null),
      tableRows: new Map(),
      lastSuggestedTop: 0,
      files: { tsv: null, rename: null, color: null }
    };

    function showMessage(message, isError = false) {
      if (!elements.message) return;
      elements.message.textContent = message;
      elements.message.classList.toggle('is-error', Boolean(isError));
    }

    function setFile(kind, file) {
      state.files[kind] = file || null;
      const nameElement = elements[`${kind}Name`];
      if (nameElement) nameElement.textContent = file ? file.name : (kind === 'tsv' ? 'No file selected' : 'Optional');
      if (elements.loadButton) elements.loadButton.disabled = !state.files.tsv;
    }

    function clearFile(kind) {
      setFile(kind, null);
      const input = elements[`${kind}Input`];
      if (input) input.value = '';
    }

    async function loadFiles() {
      if (!state.files.tsv) return;
      elements.loadButton.disabled = true;
      elements.loadButton.textContent = 'Loading…';
      showMessage('');
      const ok = await viewer.loadFromSources({
        tsv: state.files.tsv,
        rename: state.files.rename,
        color: state.files.color
      });
      elements.loadButton.textContent = 'Load files';
      elements.loadButton.disabled = !state.files.tsv;
      if (!ok) showMessage('The files could not be loaded. Review the error below the viewer.', true);
    }

    function statsMap(scope) {
      return scope === 'visible' ? state.visibleStats : state.allStats;
    }

    function metricValue(record, metric, scope) {
      const stats = statsMap(scope).get(record.rawName);
      return stats ? Number(stats[metric] || 0) : 0;
    }

    function currentStats(record) {
      const scope = elements.scope?.value === 'visible' ? 'visible' : 'all';
      return statsMap(scope).get(record.rawName) || {
        occurrences: 0,
        genes: 0,
        neighborhoods: 0
      };
    }

    function duplicateDisplayCount() {
      const counts = new Map();
      for (const record of state.records.values()) {
        const name = clean(record.displayName) || record.rawName;
        const key = lower(name);
        counts.set(key, (counts.get(key) || 0) + 1);
      }
      let duplicateNames = 0;
      for (const count of counts.values()) if (count > 1) duplicateNames += 1;
      return duplicateNames;
    }

    function updateSummary() {
      if (!elements.summary) return;
      const colored = Array.from(state.records.values()).filter(record => record.colorIncluded).length;
      const renamed = Array.from(state.records.values()).filter(record => clean(record.displayName) && record.displayName !== record.rawName).length;
      const duplicates = duplicateDisplayCount();
      elements.summary.textContent = `${numberText(state.records.size)} domains · ${numberText(colored)} colored · ${numberText(renamed)} renamed${duplicates ? ` · ${duplicates} duplicate names` : ''}`;
    }

    function sortedRecords() {
      const metric = ['occurrences', 'genes', 'neighborhoods'].includes(elements.metric?.value)
        ? elements.metric.value
        : 'genes';
      const scope = elements.scope?.value === 'visible' ? 'visible' : 'all';
      const query = lower(elements.search?.value);
      return Array.from(state.records.values())
        .filter(record => !query || lower(`${record.rawName} ${record.displayName}`).includes(query))
        .sort((a, b) => {
          const countDiff = metricValue(b, metric, scope) - metricValue(a, metric, scope);
          if (countDiff) return countDiff;
          return a.rawName.localeCompare(b.rawName);
        });
    }

    function renderTable() {
      if (!elements.tableBody) return;
      state.tableRows.clear();
      const fragment = document.createDocumentFragment();
      const records = sortedRecords();
      records.forEach((record, index) => {
        const stats = currentStats(record);
        const row = document.createElement('tr');
        row.className = `nbh-domain-row${record.rawName === state.selectedRawName ? ' is-selected' : ''}`;
        row.tabIndex = 0;
        row.dataset.domainId = record.rawName;
        row.setAttribute('aria-selected', record.rawName === state.selectedRawName ? 'true' : 'false');

        const rank = document.createElement('td');
        rank.className = 'is-number';
        rank.textContent = String(index + 1);

        const colorCell = document.createElement('td');
        const swatch = document.createElement('span');
        swatch.className = `nbh-swatch${record.colorIncluded ? '' : ' is-disabled'}`;
        swatch.style.backgroundColor = record.colorIncluded ? record.color : DEFAULT_COLOR;
        swatch.title = record.colorIncluded ? record.color : 'Not included in color YAML';
        colorCell.appendChild(swatch);

        const idCell = document.createElement('td');
        idCell.className = 'nbh-domain-id';
        idCell.textContent = record.rawName;
        idCell.title = record.rawName;
        if (record.marker) {
          const badge = document.createElement('span');
          badge.className = 'nbh-marker-badge';
          badge.textContent = 'marker';
          idCell.appendChild(badge);
        }

        const displayCell = document.createElement('td');
        displayCell.className = 'nbh-domain-display';
        displayCell.textContent = record.displayName;
        displayCell.title = record.displayName;

        const occurrenceCell = document.createElement('td');
        occurrenceCell.className = 'is-number';
        occurrenceCell.textContent = numberText(stats.occurrences);
        const geneCell = document.createElement('td');
        geneCell.className = 'is-number';
        geneCell.textContent = numberText(stats.genes);
        const neighborhoodCell = document.createElement('td');
        neighborhoodCell.className = 'is-number';
        neighborhoodCell.textContent = numberText(stats.neighborhoods);

        row.append(rank, colorCell, idCell, displayCell, occurrenceCell, geneCell, neighborhoodCell);
        row.addEventListener('click', () => selectDomain(record.rawName, true));
        row.addEventListener('keydown', event => {
          if (event.key === 'Enter' || event.key === ' ') {
            event.preventDefault();
            selectDomain(record.rawName, true);
          }
        });
        state.tableRows.set(record.rawName, row);
        fragment.appendChild(row);
      });
      elements.tableBody.replaceChildren(fragment);
      if (elements.emptyRows) elements.emptyRows.hidden = records.length > 0;
      updateSummary();
    }

    function renderSelectedEditor() {
      const record = state.records.get(state.selectedRawName);
      if (!record) {
        if (elements.editorEmpty) elements.editorEmpty.hidden = false;
        if (elements.editorForm) elements.editorForm.hidden = true;
        return;
      }
      if (elements.editorEmpty) elements.editorEmpty.hidden = true;
      if (elements.editorForm) elements.editorForm.hidden = false;
      if (elements.selectedTitle) elements.selectedTitle.textContent = record.displayName || record.rawName;
      if (elements.selectedId) elements.selectedId.textContent = record.rawName;
      if (elements.renameInputEdit) elements.renameInputEdit.value = record.displayName;
      if (elements.colorEnabled) { elements.colorEnabled.checked = record.colorIncluded; elements.colorEnabled.disabled = record.marker; }
      if (elements.colorPicker) { elements.colorPicker.value = normalizeHex(record.color).toLowerCase(); elements.colorPicker.disabled = record.marker; }
      if (elements.colorText) { elements.colorText.value = normalizeHex(record.color); elements.colorText.disabled = record.marker; }
      if (elements.resetColor) elements.resetColor.disabled = record.marker;
      if (elements.markerNote) {
        elements.markerNote.hidden = !record.marker;
        elements.markerNote.textContent = record.marker
          ? 'This domain is configured as a special marker. It is excluded from Top-N suggestions and color YAML export; marker color and geometry remain controlled by markerDomains in config.js.'
          : '';
      }
      const stats = currentStats(record);
      if (elements.countOccurrences) elements.countOccurrences.textContent = numberText(stats.occurrences);
      if (elements.countGenes) elements.countGenes.textContent = numberText(stats.genes);
      if (elements.countNeighborhoods) elements.countNeighborhoods.textContent = numberText(stats.neighborhoods);
    }

    function selectDomain(rawName, scrollTable = false) {
      if (!state.records.has(rawName)) return;
      const previous = state.tableRows.get(state.selectedRawName);
      if (previous) {
        previous.classList.remove('is-selected');
        previous.setAttribute('aria-selected', 'false');
      }
      state.selectedRawName = rawName;
      const row = state.tableRows.get(rawName);
      if (row) {
        row.classList.add('is-selected');
        row.setAttribute('aria-selected', 'true');
        if (scrollTable) row.scrollIntoView({ block: 'nearest', behavior: 'smooth' });
      } else {
        renderTable();
      }
      viewer.setHighlightedDomain(rawName);
      renderSelectedEditor();
    }

    function buildPreviewDictionaries() {
      const renames = copyObject(state.unmatchedRenames);
      const colors = copyObject(state.unmatchedColors);
      for (const record of state.records.values()) {
        if (clean(record.displayName) && record.displayName !== record.rawName) renames[record.rawName] = record.displayName;
        if (!record.marker && record.colorIncluded && validHex(record.color)) colors[record.rawName] = normalizeHex(record.color);
      }
      return { renames, colors };
    }

    let applyTimer = 0;
    function scheduleApply() {
      window.clearTimeout(applyTimer);
      applyTimer = window.setTimeout(() => {
        const dictionaries = buildPreviewDictionaries();
        try {
          viewer.updateDictionaries(dictionaries);
          showMessage('Preview updated. Download the YAML files when the curation is ready.');
        } catch (error) {
          console.error(error);
          showMessage(error?.message || 'Could not update the preview.', true);
        }
      }, 140);
    }

    function applyRecordChange(record) {
      const row = state.tableRows.get(record.rawName);
      if (row) {
        const swatch = row.querySelector('.nbh-swatch');
        if (swatch) {
          swatch.classList.toggle('is-disabled', !record.colorIncluded);
          swatch.style.backgroundColor = record.colorIncluded ? record.color : DEFAULT_COLOR;
          swatch.title = record.colorIncluded ? record.color : 'Not included in color YAML';
        }
        const display = row.querySelector('.nbh-domain-display');
        if (display) {
          display.textContent = record.displayName;
          display.title = record.displayName;
        }
      }
      if (elements.selectedTitle && state.selectedRawName === record.rawName) elements.selectedTitle.textContent = record.displayName || record.rawName;
      updateSummary();
      scheduleApply();
    }

    function initializeRecords(payload) {
      const dictionaries = payload?.dictionaries || viewer.getDictionaries();
      state.initialRenames = copyObject(dictionaries.renames);
      state.initialColors = copyObject(dictionaries.colors);
      state.unmatchedRenames = copyObject(state.initialRenames);
      state.unmatchedColors = copyObject(state.initialColors);
      state.allStats = new Map(viewer.getDomainStats({ scope: 'all' }).map(record => [record.rawName, record]));
      state.visibleStats = new Map(viewer.getDomainStats({ scope: 'visible' }).map(record => [record.rawName, record]));
      state.records.clear();

      for (const stats of state.allStats.values()) {
        const renameEntry = findMappedEntry(state.initialRenames, [stats.rawName]);
        const displayName = clean(renameEntry?.value) || stats.displayName || stats.rawName;
        const colorEntry = findMappedEntry(state.initialColors, [displayName, stats.rawName]);
        const record = {
          rawName: stats.rawName,
          displayName,
          originalDisplayName: displayName,
          color: normalizeHex(colorEntry?.value || stats.color || suggestedColor(0, stats.rawName)),
          originalColor: normalizeHex(colorEntry?.value || stats.color || DEFAULT_COLOR),
          colorIncluded: Boolean(colorEntry) && !stats.marker,
          marker: Boolean(stats.marker)
        };
        state.records.set(record.rawName, record);
        removeMappedEntries(state.unmatchedRenames, [stats.rawName]);
        if (!stats.marker) removeMappedEntries(state.unmatchedColors, [stats.rawName, displayName]);
      }

      state.loaded = true;
      state.selectedRawName = '';
      if (elements.card) elements.card.hidden = false;
      for (const button of [elements.renameDownload, elements.colorDownload, elements.bothDownload, elements.suggestButton]) {
        if (button) button.disabled = false;
      }
      renderTable();
      const first = sortedRecords()[0];
      if (first) selectDomain(first.rawName, false);
      const summary = viewer.getSummary();
      showMessage(`${numberText(state.records.size)} domains loaded from ${numberText(summary.totalNeighborhoods)} neighborhoods. Rename and color YAML files are optional.`);
    }

    function updateStatsAfterDictionaryChange() {
      state.allStats = new Map(viewer.getDomainStats({ scope: 'all' }).map(record => [record.rawName, record]));
      state.visibleStats = new Map(viewer.getDomainStats({ scope: 'visible' }).map(record => [record.rawName, record]));
      renderTable();
      renderSelectedEditor();
    }

    function suggestColors() {
      if (!state.loaded) return;
      const metric = ['occurrences', 'genes', 'neighborhoods'].includes(elements.metric?.value)
        ? elements.metric.value
        : 'genes';
      const scope = elements.scope?.value === 'visible' ? 'visible' : 'all';
      const requested = Math.max(1, Math.min(250, Number(elements.topCount?.value) || 10));
      const candidates = Array.from(state.records.values())
        .filter(record => !record.marker && metricValue(record, metric, scope) > 0)
        .sort((a, b) => metricValue(b, metric, scope) - metricValue(a, metric, scope) || a.rawName.localeCompare(b.rawName))
        .slice(0, requested);
      const preserve = elements.preserveExisting?.checked !== false;
      candidates.forEach((record, index) => {
        if (!preserve || !record.colorIncluded) record.color = suggestedColor(index, record.rawName);
        record.colorIncluded = true;
      });
      state.lastSuggestedTop = candidates.length;
      renderTable();
      renderSelectedEditor();
      scheduleApply();
      showMessage(`Suggested distinct colors for the top ${candidates.length} non-marker domains ranked by ${metric} in the ${scope === 'all' ? 'full dataset' : 'visible neighborhoods'}.`);
    }

    function exportRenameObject() {
      const object = elements.preserveUnmatched?.checked === false ? Object.create(null) : copyObject(state.unmatchedRenames);
      for (const record of state.records.values()) {
        if (clean(record.displayName) && record.displayName !== record.rawName) object[record.rawName] = record.displayName;
      }
      return object;
    }

    function exportColorObject() {
      const object = elements.preserveUnmatched?.checked === false ? Object.create(null) : copyObject(state.unmatchedColors);
      for (const record of state.records.values()) {
        if (!record.marker && record.colorIncluded && validHex(record.color)) object[record.rawName] = normalizeHex(record.color);
      }
      return object;
    }

    function exportHeader() {
      const metric = elements.metric?.value || 'genes';
      const scope = elements.scope?.value === 'visible' ? 'visible neighborhoods' : 'all loaded neighborhoods';
      return [
        `Frequency ranking: ${metric}`,
        `Ranking scope: ${scope}`,
        `Top-N suggestion last applied: ${state.lastSuggestedTop || 'not applied'}`
      ];
    }

    function downloadRename() {
      const yaml = serializeFlatYaml(exportRenameObject(), exportHeader());
      downloadBlob('domain_rename.yaml', new Blob([yaml], { type: 'text/yaml;charset=utf-8' }));
      showMessage('Downloaded domain_rename.yaml.');
    }

    function downloadColors() {
      const yaml = serializeFlatYaml(exportColorObject(), exportHeader());
      downloadBlob('color_dic.yaml', new Blob([yaml], { type: 'text/yaml;charset=utf-8' }));
      showMessage('Downloaded color_dic.yaml.');
    }

    async function downloadBoth() {
      if (!window.JSZip) {
        showMessage('The ZIP helper did not load. Download the two YAML files separately.', true);
        return;
      }
      const zip = new JSZip();
      zip.file('domain_rename.yaml', serializeFlatYaml(exportRenameObject(), exportHeader()));
      zip.file('color_dic.yaml', serializeFlatYaml(exportColorObject(), exportHeader()));
      zip.file('README.txt', [
        'Generated by EvoSupplement Gene Neighborhood Editor.',
        'Copy these files into the data/ folder of a Gene Neighborhood Viewer figure and update config.js if needed.',
        'The original domain identifiers remain the canonical YAML keys.'
      ].join('\n'));
      showMessage('Creating YAML package…');
      const blob = await zip.generateAsync({ type: 'blob', compression: 'DEFLATE', compressionOptions: { level: 6 } });
      downloadBlob('gene-neighborhood-yaml.zip', blob);
      showMessage('Downloaded gene-neighborhood-yaml.zip.');
    }

    function bindEvents() {
      elements.tsvChoose?.addEventListener('click', () => elements.tsvInput?.click());
      elements.renameChoose?.addEventListener('click', () => elements.renameInput?.click());
      elements.colorChoose?.addEventListener('click', () => elements.colorInput?.click());
      elements.tsvClear?.addEventListener('click', () => clearFile('tsv'));
      elements.renameClear?.addEventListener('click', () => clearFile('rename'));
      elements.colorClear?.addEventListener('click', () => clearFile('color'));
      elements.tsvInput?.addEventListener('change', event => setFile('tsv', event.target.files?.[0]));
      elements.renameInput?.addEventListener('change', event => setFile('rename', event.target.files?.[0]));
      elements.colorInput?.addEventListener('change', event => setFile('color', event.target.files?.[0]));
      elements.loadButton?.addEventListener('click', loadFiles);

      elements.search?.addEventListener('input', renderTable);
      elements.metric?.addEventListener('change', () => { renderTable(); renderSelectedEditor(); });
      elements.scope?.addEventListener('change', () => { renderTable(); renderSelectedEditor(); });
      elements.suggestButton?.addEventListener('click', suggestColors);
      document.querySelectorAll('[data-top-count]').forEach(button => {
        button.addEventListener('click', () => {
          if (elements.topCount) elements.topCount.value = button.dataset.topCount;
          suggestColors();
        });
      });

      elements.editMode?.addEventListener('change', event => viewer.setDomainEditMode(event.target.checked));
      elements.renameInputEdit?.addEventListener('input', event => {
        const record = state.records.get(state.selectedRawName);
        if (!record) return;
        record.displayName = clean(event.target.value) || record.rawName;
        applyRecordChange(record);
      });
      elements.resetRename?.addEventListener('click', () => {
        const record = state.records.get(state.selectedRawName);
        if (!record) return;
        record.displayName = record.rawName;
        renderSelectedEditor();
        applyRecordChange(record);
      });
      elements.colorEnabled?.addEventListener('change', event => {
        const record = state.records.get(state.selectedRawName);
        if (!record || record.marker) return;
        record.colorIncluded = event.target.checked;
        applyRecordChange(record);
      });
      elements.colorPicker?.addEventListener('input', event => {
        const record = state.records.get(state.selectedRawName);
        if (!record || record.marker) return;
        record.color = normalizeHex(event.target.value);
        record.colorIncluded = true;
        if (elements.colorText) elements.colorText.value = record.color;
        if (elements.colorEnabled) elements.colorEnabled.checked = true;
        applyRecordChange(record);
      });
      elements.colorText?.addEventListener('change', event => {
        const record = state.records.get(state.selectedRawName);
        if (!record || record.marker) return;
        const normalized = normalizeHex(event.target.value, '');
        if (!normalized) {
          showMessage('Enter a hexadecimal color such as #4E79A7.', true);
          event.target.value = record.color;
          return;
        }
        record.color = normalized;
        record.colorIncluded = true;
        if (elements.colorPicker) elements.colorPicker.value = normalized.toLowerCase();
        if (elements.colorEnabled) elements.colorEnabled.checked = true;
        applyRecordChange(record);
      });
      elements.resetColor?.addEventListener('click', () => {
        const record = state.records.get(state.selectedRawName);
        if (!record || record.marker) return;
        record.colorIncluded = false;
        record.color = record.originalColor || DEFAULT_COLOR;
        renderSelectedEditor();
        applyRecordChange(record);
      });
      elements.renameDownload?.addEventListener('click', downloadRename);
      elements.colorDownload?.addEventListener('click', downloadColors);
      elements.bothDownload?.addEventListener('click', downloadBoth);
    }

    bindEvents();
    if (elements.editMode) viewer.setDomainEditMode(elements.editMode.checked);

    viewer.onDomainSelect(payload => selectDomain(payload.rawName, true));
    viewer.onVisibleChange(payload => {
      state.visibleStats = new Map((payload.domainStats || []).map(record => [record.rawName, record]));
      if (elements.scope?.value === 'visible') {
        renderTable();
        renderSelectedEditor();
      }
    });
    viewer.onDataChange(payload => {
      if (payload.reason === 'dictionary-update') {
        updateStatsAfterDictionaryChange();
        return;
      }
      initializeRecords(payload);
    });

    return {
      loadFiles,
      selectDomain,
      getState: () => state
    };
  }

  window.NeighborhoodDomainEditor = {
    version: EDITOR_VERSION,
    init(options) {
      if (!window.NeighborhoodViewer) throw new Error('NeighborhoodViewer must be initialized before NeighborhoodDomainEditor.');
      return createEditor(window.NeighborhoodViewer, options);
    }
  };
})();
